"""Generates the Looks shader table for Apex Radiance from the ported shaders in third_party/reshade_shaders.

For each shader in SPECS it reads third_party/reshade_shaders/<Name>.hlsl (the port: the author's .fx from the
repository named in LICENSES.md, with its uniforms in constant registers and its techniques replaced by ps_3_0 entry
wrappers at the end), compiles it with fxc after shaders/looks_common.hlsl as a check, and writes
third_party/reshade_shaders/reshade_shaders_hlsl.h (HLSL pieces, entry points, parameter tables, menu text).

The parameter tables (ui_label, defaults, ui_min / ui_max, combo items) come from the .fx annotations, which the
ported .hlsl no longer carries: they are carried over from the header this script wrote before, checked against the
authors' .fx files. Run (fxc from the Windows SDK, or FXC=<path>):
  python -I tools/looks_shaders_gen.py
"""
import glob, os, re, subprocess, sys

APEX = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DIR = os.path.join(APEX, "third_party", "reshade_shaders")
HEADER = os.path.join(DIR, "reshade_shaders_hlsl.h")
COMMON = os.path.join(APEX, "shaders", "looks_common.hlsl")


def find_fxc():
    if os.environ.get("FXC"):
        return os.environ["FXC"]
    kits = sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe"))
    if not kits:
        raise SystemExit("fxc.exe not found: set FXC")
    return kits[-1]


# name = the .hlsl file; kind: Color, Sharpen, Light, Film, Stylized (the menu's Kind filter); desc: one menu line
SPECS = [
    dict(name="Levels", technique="Levels", file="Levels.fx", kind="Color", desc="Black and white points"),
    dict(name="Technicolor2", technique="Technicolor2", file="Technicolor2.fx", kind="Film", desc="Bold three-strip film colors"),
    dict(name="RetroTint", technique="RetroTint", file="RetroTint.fx", kind="Stylized", desc="Old photo tint"),
    dict(name="DPX", technique="DPX", file="DPX.fx", kind="Film", desc="Film print colors"),
    dict(name="AdaptiveSharpen", technique="AdaptiveSharpen", file="AdaptiveSharpen.fx", kind="Sharpen", desc="Sharper edges"),
    dict(name="Vibrance", technique="Vibrance", file="Vibrance.fx", kind="Color", desc="Strength of dull colors"),
    dict(name="Tint", technique="Tint", file="Sepia.fx", kind="Stylized", desc="Warm tint"),
    dict(name="Tonemap", technique="Tonemap", file="Tonemap.fx", kind="Light", desc="Exposure and saturation"),
    dict(name="Colourfulness", technique="Colourfulness", file="Colourfulness.fx", kind="Color", desc="Richer color"),
    dict(name="LumaSharpen", technique="LumaSharpen", file="LumaSharpen.fx", kind="Sharpen", desc="Sharper detail"),
    dict(name="CAS", technique="ContrastAdaptiveSharpen", file="CAS.fx", kind="Sharpen", desc="Sharper textures",
         srgb=True),  # sRGB sampler on COLOR + SRGBWriteEnable, as in the .fx
    dict(name="Curves", technique="Curves", file="Curves.fx", kind="Color", desc="Contrast curve"),
    dict(name="Vignette", technique="Vignette", file="Vignette.fx", kind="Film", desc="Darker corners"),
    dict(name="Technicolor", technique="Technicolor", file="Technicolor.fx", kind="Film", desc="Strong film colors"),
    dict(name="FakeHDR", technique="HDR", file="FakeHDR.fx", kind="Light", desc="More range in light and shade"),
    dict(name="PD80SelectiveColor", technique="prod80_04_SelectiveColor", file="PD80_04_Selective_Color.fx", kind="Color",
         desc="Adjust one color family"),
    dict(name="LiftGammaGain", technique="LiftGammaGain", file="LiftGammaGain.fx", kind="Color",
         desc="Shadows, midtones and highlights"),
]


def old_params():
    """name -> the rows of k<Name>Params[] in the header written before (the .fx annotations)."""
    text = open(HEADER, encoding="utf-8").read()
    return {m.group(1): m.group(2).rstrip("\n") for m in re.finditer(r"static const \w+ k(\w+)Params\[\] = \{\n(.*?)\n\};", text, re.S)}


def body_of(spec):
    body = open(os.path.join(DIR, spec["name"] + ".hlsl"), encoding="utf-8").read().replace("\r\n", "\n")
    entries = re.findall(r"^float4 (gs_\w+)\(float2 vp : VPOS", body, re.M)
    if not entries:
        raise SystemExit("%s.hlsl: no ps_3_0 entry point" % spec["name"])
    return body, entries


def cpp_str_pieces(text, size=12000):
    return ['R"GSHLSL(%s)GSHLSL"' % text[i:i + size] for i in range(0, len(text), size)]


def main():
    fxc = find_fxc()
    common = open(COMMON, encoding="utf-8").read().replace("\r\n", "\n")
    params = old_params()
    h = ["// Generated by tools/looks_shaders_gen.py from third_party/reshade_shaders/*.hlsl, ports of ReShade shaders from "
         "their authors' repositories under the licences in LICENSES.md. Do not edit by hand.",
         "#pragma once", '#include "looks_shaders.h"', "", "namespace ReShadeShaders {", ""]
    h.append("static const char* const kCommon[] = { %s, nullptr };" % ", ".join(cpp_str_pieces(common)))
    table, ok = [], True
    for spec in SPECS:
        n = spec["name"]
        body, entries = body_of(spec)
        rows = params.get(n)
        if rows is None:
            raise SystemExit("%s: no parameter table in the previous header" % n)
        rows = rows.replace("GsKind::", "LooksParamKind::")
        check = os.path.join(DIR, "~%s.check.hlsl" % n)
        open(check, "w", encoding="utf-8", newline="\n").write(common + body)
        try:
            for e in entries:
                r = subprocess.run([fxc, "/nologo", "/T", "ps_3_0", "/E", e, "/O3", "/Fo", os.devnull, check], capture_output=True, text=True)
                print("%-20s %-28s %s" % (n, e, "ok" if r.returncode == 0 else "FAILED"))
                if r.returncode:
                    ok = False
                    print(r.stderr[-3000:])
        finally:
            os.remove(check)
        count = len(re.findall(r'^    \{ "', rows, re.M))
        h.append("static const char* const k%sSrc[] = { %s, nullptr };" % (n, ", ".join(cpp_str_pieces(body))))
        h.append("static const char* const k%sEntries[] = { %s, nullptr };" % (n, ", ".join('"%s"' % e for e in entries)))
        h.append("static const LooksParam k%sParams[] = {\n%s\n};" % (n, rows))
        table.append('    { "%s", "%s", k%sSrc, k%sEntries, k%sParams, %d, %s, %s, "%s", LooksShaderKind::%s },' % (
            spec["technique"], spec["file"], n, n, n, count, "true" if spec.get("depth") else "false",
            "true" if spec.get("srgb") else "false", spec["desc"], spec["kind"]))
    h.append("")
    h.append("static const LooksShader kShaders[] = {\n%s\n};" % "\n".join(table))
    h.append("static const int kShaderCount = %d;" % len(SPECS))
    h.append("} // namespace ReShadeShaders")
    if not ok:
        print("SOME SHADERS FAILED: header not written")
        sys.exit(1)
    open(HEADER, "w", encoding="utf-8", newline="\n").write("\n".join(h) + "\n")
    print("ok: %d shaders" % len(SPECS))


if __name__ == "__main__":
    main()
